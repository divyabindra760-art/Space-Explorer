/**
 * Fetch live position telemetry for the International Space Station
 */
export async function fetchISSPosition() {
  try {
    const response = await fetch(ISS_API_URL);
    if (!response.ok) {
      throw new Error(`ISS API network error: ${response.status}`);
    }
    const data = await response.json();
    return {
      latitude: data.latitude,
      longitude: data.longitude,
      altitude: Math.round(data.altitude), // in km
      velocity: Math.round(data.velocity), // in km/h
      visibility: data.visibility,
      timestamp: data.timestamp,
      isLive: true
    };
  } catch (error) {
    console.warn("ISS Live API warning, using estimated orbital simulation:", error.message);
    // Calculated smooth orbital position simulation if network API is offline
    const now = Date.now() / 1000;
    const lat = Math.sin(now / 500) * 51.6; // ISS orbital inclination ~51.6 deg
    const lon = ((now / 20) % 360) - 180;
    return {
      latitude: Number(lat.toFixed(4)),
      longitude: Number(lon.toFixed(4)),
      altitude: 418,
      velocity: 27580,
      visibility: "daylight",
      timestamp: Math.floor(Date.now() / 1000),
      isLive: false,
      note: "Simulated orbital telemetry (Offline mode)"
    };
  }
}

/**
 * Fetch NASA Astronomy Picture of the Day for a given date
 */
export async function fetchNASA_APOD(dateString = null) {
  try {
    let url = NASA_APOD_URL;
    if (dateString) {
      url += `&date=${dateString}`;
    }
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`NASA APOD API status: ${response.status}`);
    }
    const data = await response.json();
    return data;
  } catch (error) {
    console.warn("NASA APOD fallback invoked:", error.message);
    // Return appropriate fallback item
    const fallbackIndex = Math.abs((dateString ? dateString.length : 0)) % APOD_FALLBACKS.length;
    return APOD_FALLBACKS[fallbackIndex];
  }
}
